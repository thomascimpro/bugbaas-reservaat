import {readFile,writeFile,mkdir,stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,join} from 'node:path';
import sharp from 'sharp';

// Run after the HD portrait renderer/encoder has completed its entire batch.
const root=fileURLToPath(new URL('../',import.meta.url));
const source=resolve(root,'assets/v2/portraits/v1'),output=resolve(root,'assets/v2/portraits/thumbs');
const manifest=JSON.parse(await readFile(join(source,'manifest.json'),'utf8'));
const ids=Object.keys(manifest.species??{}).sort();if(ids.length!==150)throw new Error('The completed 150-species HD portrait manifest is required.');
const images=[];let hdBytes=0;
for(const id of ids){
 if(!/^[a-z0-9_]+$/.test(id))throw new Error('Unexpected portrait ID.');
 for(const shiny of [false,true]){
  const name=id+(shiny?'-shiny':'');
  if(manifest.species[id][shiny?'shiny':'normal']!==name+'.png')throw new Error('Portrait manifest filename differs for '+name);
  const png=await readFile(join(source,name+'.png')),meta=await sharp(png).metadata(),webp=await stat(join(source,name+'.webp'));
  if(meta.width!==1024||meta.height!==1024||!meta.hasAlpha)throw new Error('Expected completed transparent 1024px portrait for '+name);
  images.push({name,png});hdBytes+=webp.size;
 }
}
// Preflight all sources before touching thumbnails or their static Metro require map.
await mkdir(output,{recursive:true});let thumbBytes=0;
for(const image of images){
 const {data,info}=await sharp(image.png).resize(256,256,{fit:'contain',background:{r:0,g:0,b:0,alpha:0}}).webp({quality:80,alphaQuality:100,effort:3}).toBuffer({resolveWithObject:true});
 if(info.width!==256||info.height!==256||!(await sharp(data).metadata()).hasAlpha)throw new Error('Thumbnail dimensions or transparency differ for '+image.name);
 await writeFile(join(output,image.name+'.webp'),data);thumbBytes+=data.length;
}
const rows=ids.map(id=>` '${id}':[require('../assets/v2/portraits/thumbs/${id}.webp'),require('../assets/v2/portraits/thumbs/${id}-shiny.webp')],`);
await writeFile(resolve(root,'src/portraitThumbsV2.ts'),[
 "import type {ImageSourcePropType} from 'react-native';",
 '// Generated by scripts/build-portrait-thumbs.mjs. Full HD portraits stay available for detail views.',
 'export const portraitThumbs:Record<string,readonly [ImageSourcePropType,ImageSourcePropType]>={',
 ...rows,'};','',
].join('\n'));
console.log(JSON.stringify({species:ids.length,variants:images.length,size:256,transparent:true,hdWebPBytes:hdBytes,thumbnailWebPBytes:thumbBytes,byteReductionPercent:Number((100*(1-thumbBytes/hdBytes)).toFixed(2)),hdToThumbRatio:Number((hdBytes/thumbBytes).toFixed(2)),decodedPixelReduction:16}));
